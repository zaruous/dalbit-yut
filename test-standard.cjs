const assert=require('node:assert/strict');
const M=require('./build-test/mapEngine.js'),E=require('./build-test/gameEngine.js');
const graph=M.makeGraph('S');
assert.equal(E.createGame({}).config.board,'S','The standard board is the engine default');
assert.equal(graph.outerIds.length,20);
assert.equal(Object.keys(graph.xy).length,29,'20 outer + 8 diagonal + 1 center nodes');
assert.deepEqual(graph.cornerIds,['O0','O5','O10','O15']);
assert.deepEqual(M.validateGraph(graph),[]);
for(const id of graph.outerIds){const p=graph.xy[id];assert(p.x===80||p.x===420||p.y===65||p.y===405,'Outer nodes must form a square')}
let state=M.initialState();
for(let i=0;i<4;i++)state=M.movePiece(graph,state,5,M.getOptions(graph,state).some(o=>o.value==='outer')?'outer':undefined);
assert.equal(state.node,'O0','Twenty forward steps reach the home checkpoint');
assert.equal(M.movePiece(graph,state,1).node,'FIN','A later forward step passes home and finishes');
const first=M.movePiece(graph,M.initialState(),1),back=M.movePiece(graph,first,-1);
assert.equal(back.node,'O0');
assert.equal(M.movePiece(graph,back,-1).node,'O19','Backdo follows the standard board last edge');
assert.equal(M.movePiece(graph,M.movePiece(graph,back,-1),-1).node,'O18');
const east=M.movePiece(graph,M.initialState(),5);
assert.equal(east.node,'O5');
assert.equal(M.movePiece(graph,east,1).node,'NE1','Exact first corner stop offers shortcut');
assert.equal(M.movePiece(graph,east,1,'outer').node,'O6');
const center=M.movePiece(graph,east,3,'shortcut');
assert.equal(center.node,'C');assert.equal(center.lane,'ne');
assert.equal(M.movePiece(graph,center,1).node,'SE1','Center stop defaults toward home');
assert.equal(M.movePiece(graph,center,1,'straight').node,'SW1');
assert.equal(M.movePiece(graph,east,4,'shortcut').node,'SW1','Passing center continues straight');
assert.equal(M.movePiece(graph,{...M.initialState(),node:'O4'},2).node,'O6','Passing a corner does not enter shortcut');
const west=M.movePiece(graph,east,5,'outer');
assert.equal(west.node,'O10');
assert.equal(M.movePiece(graph,west,1).node,'NW1');
assert.equal(M.movePiece(graph,M.movePiece(graph,west,3,'shortcut'),1).node,'SE1');
const original=JSON.stringify(center),reverse=M.movePiece(graph,center,-1);
assert.equal(reverse.node,'NE2');assert.equal(JSON.stringify(center),original,'Backdo must not mutate prior state');
const game=E.createGame({mode:'spectate',count:4,board:'S'});
game.pieces[0]={...game.pieces[0],...east};game.pieces[1]={...game.pieces[1],...east};
game.pieces[4]={...game.pieces[4],...center};game.phase='move';game.rolls=[{id:'center-capture',value:3,faces:[]}];
const options=E.moveOptions(game,'p0-0','center-capture');
assert.equal(game.pieces[0].node,'O5','Selecting a route alone must not move a piece');
const capture=E.resolveMove(game,options.find(o=>o.choice==='shortcut'));
assert.equal(capture.meta.moved,2);assert.equal(capture.meta.captured,1);
assert.equal(capture.game.pieces[0].node,'C');assert.equal(capture.game.pieces[4].node,'WAIT');
assert.equal(capture.game.phase,'roll');assert.equal(capture.game.current,0);
const win=E.createGame({board:'S'});
for(let i=0;i<4;i++)win.pieces[i]={...win.pieces[i],...state};
win.phase='move';win.rolls=[{id:'finish',value:1,faces:[]}];
const result=E.resolveMove(win,E.moveOptions(win,'p0-0','finish')[0]);
assert.equal(result.meta.moved,4);assert.equal(result.game.winner,0);
console.log('OK: standard square, 29 nodes, 20 outer steps, shortcuts, center, backdo, stacked capture and win');
